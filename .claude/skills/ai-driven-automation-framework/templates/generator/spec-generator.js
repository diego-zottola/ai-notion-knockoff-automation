import { createWorkManagement } from '../connectors/work-management.factory.js';

/**
 * Generates a Playwright spec file from a ticket.
 * @param {import('../connectors/work-management.interface.js').Ticket} ticket
 * @returns {{ specPath: string, specContent: string, pageObjectPath: string, pageObjectContent: string }}
 */
export function generateSpec(ticket) {
  const slug = slugify(ticket.id);
  const pageName = `${pascalCase(ticket.title)}Page`;
  const specPath = `tests/regression/${slug}.spec.ts`;
  const pageObjectPath = `pages/${pageName}.ts`;

  const specContent = buildSpec(ticket, pageName);
  const pageObjectContent = buildPageObject(pageName);

  return { specPath, specContent, pageObjectPath, pageObjectContent };
}

/**
 * Fetches all Ready-for-QA tickets and generates specs for each.
 * Returns an array of generation results.
 */
export async function generateFromReadyTickets() {
  const wm = createWorkManagement();
  const tickets = await wm.listReadyForQA();
  return tickets.map(ticket => ({
    ticket,
    ...generateSpec(ticket),
  }));
}

/**
 * Anti-tautological gate.
 * Verifies the generated spec contains at least one assertion
 * that references a value from the ticket's acceptance criteria.
 * A spec that only navigates and takes screenshots always passes — that's a tautology.
 * @param {string} specContent
 * @param {string[]} acceptanceCriteria
 * @returns {{ passes: boolean, reason: string }}
 */
export function antiTautologicalGate(specContent, acceptanceCriteria) {
  // Must have at least one expect() call
  if (!/expect\s*\(/.test(specContent)) {
    return { passes: false, reason: 'No expect() calls found — spec cannot fail' };
  }

  // Must have at least one assertion referencing AC content
  const hasACReference = acceptanceCriteria.some(ac => {
    const keywords = ac.split(/\s+/).filter(w => w.length > 4);
    return keywords.some(kw => specContent.includes(kw));
  });

  if (!hasACReference && acceptanceCriteria.length > 0) {
    return {
      passes: false,
      reason: 'No assertion references acceptance criteria — spec may not test the right thing',
    };
  }

  return { passes: true, reason: 'Gate passed' };
}

// ── SPEC BUILDER ─────────────────────────────────────────────────────────

function buildSpec(ticket, pageName) {
  const acTests = ticket.acceptanceCriteria.length > 0
    ? ticket.acceptanceCriteria.map((ac, i) => buildACTest(ac, i, pageName)).join('\n\n')
    : buildDefaultTest(ticket.title, pageName);

  return `// Generated by Generator Agent from ticket: ${ticket.id}
// Title: ${ticket.title}
// URL: ${ticket.url}
//
// REVIEW BEFORE MERGING:
// 1. Verify each assertion matches actual UI behavior
// 2. Replace placeholder selectors with real data-testid values
// 3. Run locally to confirm at least one assertion can fail

import { test, expect } from '@playwright/test';
import { ${pageName} } from '../../pages/${pageName}';

test.describe('${ticket.title} [${ticket.id}]', () => {

${acTests}

});
`;
}

function buildACTest(ac, index, pageName) {
  const testId = `TC_${String(index + 1).padStart(3, '0')}`;
  // Extract key action words for the assertion
  const isVisible = /visible|display|show|appear/i.test(ac);
  const isEnabled = /enabled|clickable|active/i.test(ac);
  const hasText = /text|label|message|title/i.test(ac);

  let assertion = '';
  if (isVisible) assertion = `await expect(page.locator('{{SELECTOR}}')).toBeVisible();`;
  else if (isEnabled) assertion = `await expect(page.locator('{{SELECTOR}}')).toBeEnabled();`;
  else if (hasText) assertion = `await expect(page.locator('{{SELECTOR}}')).toContainText('{{EXPECTED_TEXT}}');`;
  else assertion = `await expect(page.locator('{{SELECTOR}}')).toBeVisible(); // TODO: refine assertion for: ${ac}`;

  return `  test('${testId}: ${ac}', async ({ page }) => {
    const ${pageName.toLowerCase()} = new ${pageName}(page);
    await ${pageName.toLowerCase()}.navigate();

    // AC: ${ac}
    ${assertion}
  });`;
}

function buildDefaultTest(title, pageName) {
  return `  test('should satisfy acceptance criteria for: ${title}', async ({ page }) => {
    const ${pageName.toLowerCase()} = new ${pageName}(page);
    await ${pageName.toLowerCase()}.navigate();

    // TODO: add assertions based on acceptance criteria
    await expect(page).toHaveTitle(/.+/);
  });`;
}

