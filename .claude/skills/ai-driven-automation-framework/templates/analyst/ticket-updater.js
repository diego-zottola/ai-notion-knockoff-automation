// Analyst Agent — Ticket updater.
// Reads the analyst report and writes diagnosis results back to tickets
// via the Work Management Connector. Closes the loop between CI and the ticket tracker.
//
// Flow:
//   generateReport() → ticketUpdates[] → postReportToTickets() → WM Connector → ticket updated

import { createWorkManagement } from '../connectors/work-management.factory.js';
import { readReport } from './reporter.js';

/**
 * Posts all high-severity diagnoses from the last analyst report
 * back to their corresponding tickets.
 *
 * Ticket ID is extracted from the test title — tests generated by the
 * Generator agent follow the pattern: "TC_001: <ac> [TICKET-123]"
 *
 * @param {object} [report] - optional report object; reads from disk if not provided
 * @returns {Promise<{ posted: number, skipped: number, errors: string[] }>}
 */
export async function postReportToTickets(report) {
  const r = report ?? readReport();
  if (!r) {
    console.warn('[ticket-updater] No report found — run generateReport() first');
    return { posted: 0, skipped: 0, errors: [] };
  }

  const wm = createWorkManagement();
  let posted = 0, skipped = 0;
  const errors = [];

  for (const update of r.ticketUpdates ?? []) {
    const ticketId = extractTicketId(update.testTitle);
    if (!ticketId) {
      skipped++;
      continue;
    }
    try {
      await wm.updateTicket(ticketId, { comment: update.body });
      posted++;
      console.log(`[ticket-updater] Posted to ${ticketId}: ${update.testTitle}`);
    } catch (err) {
      errors.push(`${ticketId}: ${err.message}`);
      console.error(`[ticket-updater] Failed to post to ${ticketId}:`, err.message);
    }
  }

  // Also attach the full report as evidence on each affected ticket
  if (r.summary?.failures > 0) {
    const affectedTickets = [...new Set(
      (r.ticketUpdates ?? [])
        .map(u => extractTicketId(u.testTitle))
        .filter(Boolean)
    )];

    for (const ticketId of affectedTickets) {
      try {
        await wm.attachEvidence(ticketId, {
          type: 'report',
          description: `Analyst report — run ${r.runId} — ${r.summary.failures} failures`,
          path: process.env.ANALYST_REPORT_PATH ?? 'analyst-report.json',
        });
      } catch (err) {
        errors.push(`${ticketId} (evidence): ${err.message}`);
      }
    }
  }

  console.log(`[ticket-updater] Done — posted: ${posted}, skipped: ${skipped}, errors: ${errors.length}`);
  return { posted, skipped, errors };
}

/**
 * Marks a ticket as "Automation Verified" when its test passes.
 * Called after a successful CI run for tests that were previously failing.
 *
 * @param {string} testTitle - must contain a ticket ID in brackets e.g. "[VAL-123]"
 * @param {string} runId
 */
export async function markVerified(testTitle, runId) {
  const ticketId = extractTicketId(testTitle);
  if (!ticketId) return;

  const wm = createWorkManagement();
  await wm.updateTicket(ticketId, {
    comment: `✅ Automated test passed — *${testTitle}*\nRun: ${runId ?? process.env.GITHUB_RUN_ID ?? 'local'}`,
  });
}

/**
 * Extracts a ticket ID from a test title.
 * Supports patterns: [VAL-123], [PROJ-456], (VAL-123), VAL-123 at end
 */
export function extractTicketId(testTitle) {
  if (!testTitle) return null;
  const match =
    testTitle.match(/\[([A-Z]+-\d+)\]/) ??
    testTitle.match(/\(([A-Z]+-\d+)\)/) ??
    testTitle.match(/([A-Z]+-\d+)$/);
  return match?.[1] ?? null;
}
